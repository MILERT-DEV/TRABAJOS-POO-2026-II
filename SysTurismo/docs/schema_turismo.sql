-- SysTurismo - esquema H2 (idempotente: se puede ejecutar en cada arranque)
-- Modelo: perfil -> usuario, destino -> paquete <- guia, turista -> reserva <- paquete, reserva -> pago

CREATE TABLE IF NOT EXISTS perfil (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(20) NOT NULL UNIQUE,
    codigo    VARCHAR(10) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario         VARCHAR(20) NOT NULL UNIQUE,
    nombre_completo VARCHAR(80) NOT NULL,
    clave           VARCHAR(200) NOT NULL,
    estado          VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    id_perfil       INTEGER NOT NULL REFERENCES perfil (id_perfil),
    CONSTRAINT ck_usuario_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS destino (
    id_destino   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(80) NOT NULL,
    pais         VARCHAR(40) NOT NULL,
    ciudad       VARCHAR(60) NOT NULL,
    tipo_destino VARCHAR(20) NOT NULL,
    descripcion  VARCHAR(300),
    estado       VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_destino_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS guia (
    id_guia  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres  VARCHAR(80) NOT NULL,
    dni      VARCHAR(8) NOT NULL UNIQUE,
    telefono VARCHAR(9) NOT NULL,
    email    VARCHAR(80) NOT NULL,
    idiomas  VARCHAR(100) NOT NULL,
    estado   VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_guia_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS paquete (
    id_paquete    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(80) NOT NULL,
    id_destino    INTEGER NOT NULL REFERENCES destino (id_destino),
    id_guia       INTEGER NOT NULL REFERENCES guia (id_guia),
    duracion_dias INTEGER NOT NULL,
    precio        DECIMAL(10, 2) NOT NULL,
    cupo_maximo   INTEGER NOT NULL,
    dificultad    VARCHAR(10) NOT NULL,
    incluye       VARCHAR(300),
    estado        VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    CONSTRAINT ck_paquete_precio CHECK (precio > 0),
    CONSTRAINT ck_paquete_cupo CHECK (cupo_maximo > 0),
    CONSTRAINT ck_paquete_dias CHECK (duracion_dias > 0),
    CONSTRAINT ck_paquete_estado CHECK (estado IN ('ACTIVO', 'INACTIVO'))
);

CREATE TABLE IF NOT EXISTS turista (
    id_turista     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(20) NOT NULL,
    nro_documento  VARCHAR(15) NOT NULL UNIQUE,
    nombres        VARCHAR(60) NOT NULL,
    apellidos      VARCHAR(60) NOT NULL,
    email          VARCHAR(80) NOT NULL,
    telefono       VARCHAR(15) NOT NULL,
    nacionalidad   VARCHAR(40) NOT NULL
);

CREATE TABLE IF NOT EXISTS reserva (
    id_reserva    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_turista    INTEGER NOT NULL REFERENCES turista (id_turista),
    id_paquete    INTEGER NOT NULL REFERENCES paquete (id_paquete),
    id_usuario    INTEGER NOT NULL REFERENCES usuario (id_usuario),
    fecha_reserva DATE NOT NULL,
    fecha_viaje   DATE NOT NULL,
    num_personas  INTEGER NOT NULL,
    precio_total  DECIMAL(10, 2) NOT NULL,
    estado        VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',
    CONSTRAINT ck_reserva_personas CHECK (num_personas > 0),
    CONSTRAINT ck_reserva_estado CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA'))
);

CREATE TABLE IF NOT EXISTS pago (
    id_pago    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva INTEGER NOT NULL REFERENCES reserva (id_reserva),
    monto      DECIMAL(10, 2) NOT NULL,
    metodo     VARCHAR(15) NOT NULL,
    fecha_pago DATE NOT NULL,
    CONSTRAINT ck_pago_monto CHECK (monto > 0)
);

CREATE INDEX IF NOT EXISTS idx_paquete_destino ON paquete (id_destino);
CREATE INDEX IF NOT EXISTS idx_reserva_paquete_fecha ON reserva (id_paquete, fecha_viaje);
CREATE INDEX IF NOT EXISTS idx_reserva_turista ON reserva (id_turista);
CREATE INDEX IF NOT EXISTS idx_pago_reserva ON pago (id_reserva);

-- Datos iniciales: los tres perfiles del sistema
MERGE INTO perfil (id_perfil, nombre, codigo) KEY (id_perfil) VALUES
    (1, 'Root', 'ROOT'),
    (2, 'Administrador', 'ADM'),
    (3, 'Agente', 'AGT');
